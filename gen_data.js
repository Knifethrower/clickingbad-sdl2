// Generates data.h from the original game.js (the `var pd = {...};` block).
// Usage: node gen_data.js upstream/templates/game.js > data.h
'use strict';
const fs = require('fs');
const src = fs.readFileSync(process.argv[2], 'utf8');
const start = src.indexOf('var pd = {');
const end = src.indexOf('\n    };', start);
const pd = new Function(src.slice(start, end + 7).replace('var pd =', 'return ') )();

const cstr = s => '"' + String(s).replace(/\s+/g, ' ').trim()
    .replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
const num = n => { const s = String(n); return /[.e]/.test(s) ? s : s + '.0'; };

// Display order of the web version: stable ascending sort, then prepended (= descending).
function order(obj, keyfn) {
    return Object.keys(obj).map(k => [k, keyfn(obj[k])])
        .sort((a, b) => a[1] - b[1]).map(x => x[0]).reverse();
}
const cats = {
    clickers: order(pd.clickers, o => o.base_cost),
    sellers: order(pd.sellers, o => o.base_cost),
    banks: order(pd.banks, o => o.cost),
};
const catId = { clickers: 'CAT_CLICKERS', sellers: 'CAT_SELLERS', banks: 'CAT_BANKS' };
const upgKeys = order(pd.upgrades, o => o.cost);
const acKeys = order(pd.achievements, o => o.group);

let out = '/* Generated by gen_data.js from the original Clicking Bad game.js (MIT, Aaron Meier). */\n';

for (const c of Object.keys(cats)) {
    out += `static const ItemDef ${c}_def[] = {\n`;
    for (const k of cats[c]) {
        const o = pd[c][k];
        out += `    { ${cstr(k)}, ${cstr(o.sid)}, ${cstr(o.label)}, ${cstr(o.description)},\n`
            + `      ${num(o.rps)}, ${num(o.risk || 0)}, ${num(o.base_cost)}, ${num(o.unlock_rps)}, ${o.unlocked ? 1 : 0} },\n`;
    }
    out += '};\n';
}

const simple = { make_amount: 'A_MAKE_AMOUNT', make_rps_multiplier: 'A_MAKE_MULT',
    sell_amount: 'A_SELL_AMOUNT', sell_rps_multiplier: 'A_SELL_MULT', widget_roi: 'A_WIDGET_ROI' };
out += 'static const UpgradeDef upgrades_def[] = {\n';
for (const k of upgKeys) {
    const u = pd.upgrades[k];
    let act, cat = 'CAT_NONE', idx = -1;
    const p = u.action ? u.action.split('.') : ['none'];
    if (p[0] === 'none') act = 'A_NONE';
    else if (p.length === 1) act = simple[p[0]];
    else {
        act = p[2] === 'rps' ? 'A_ITEM_RPS' : p[2] === 'risk' ? 'A_ITEM_RISK' : null;
        cat = catId[p[0]]; idx = cats[p[0]].indexOf(p[1]);
    }
    if (!act || (p.length > 1 && idx < 0)) throw new Error('upgrade action ' + u.action);
    let pre = -1;
    if (u.prereq === 'hidden') pre = -2;
    else if (u.prereq) { pre = upgKeys.indexOf(u.prereq); if (pre < 0) pre = -1; }
    out += `    { ${cstr(k)}, ${cstr(u.sid)}, ${cstr(u.label)}, ${cstr(u.description)},\n`
        + `      ${num(u.cost)}, ${num(u.mod)}, ${act}, ${cat}, ${idx}, ${pre}, ${u.purchased ? 1 : 0} },\n`;
}
out += '};\n';

const statIds = ['hand_made_widgets', 'total_cash', 'total_spent', 'seconds_played',
    'cheated_cash', 'cheated_widgets'];
out += 'static const AchDef achievements_def[] = {\n';
for (const k of acKeys) {
    const a = pd.achievements[k];
    const p = a.property.split('.');
    let kind, cat = 'CAT_NONE', idx = -1;
    if (p[0] === 'stats') { kind = 'P_STAT'; idx = statIds.indexOf(p[1]); }
    else { kind = 'P_AMOUNT'; cat = catId[p[0]]; idx = cats[p[0]].indexOf(p[1]); }
    if (idx < 0 || p.length > 1 && p[0] !== 'stats' && p[2] !== 'amount') throw new Error('ach ' + a.property);
    out += `    { ${cstr(k)}, ${cstr(a.sid)}, ${cstr(a.label)}, ${cstr(a.description)},\n`
        + `      ${kind}, ${cat}, ${idx}, ${num(a.required)}, ${a.hidden ? 1 : 0} },\n`;
}
out += '};\n';

out += 'static const Quality qualities[] = {\n';
for (const q of Object.keys(pd.widgets.qualities).map(Number).sort((a, b) => a - b))
    out += `    { ${num(q)}, ${cstr(pd.widgets.qualities[q])} },\n`;
out += '};\n';

out += 'static const RiskLevel risk_levels[] = {\n';
for (const r of pd.risk_levels) out += `    { ${num(r.level)}, ${cstr(r.label)} },\n`;
out += '};\n';

out += 'static const EventDef events_def[] = {\n';
for (const k of Object.keys(pd.events)) {
    const m = /^(\w+)\(([^)]*)\)$/.exec(pd.events[k].action);
    out += `    { ${num(pd.events[k].chance)}, EV_${m[1].replace('event_', '').toUpperCase()}, ${num(m[2] || 0)} },\n`;
}
out += '};\n';
out += `#define START_SELL_RETURN ${num(pd.sell_return)}\n#define START_WIDGET_ROI ${num(pd.widget_roi)}\n`;
process.stdout.write(out);
